/**
 * Детерминированный генератор. Город обязан быть воспроизводимым:
 * один и тот же сид даёт ту же застройку при каждом рендере и на каждой машине.
 * Math.random() здесь использовать нельзя.
 */
export function createRandom(seed: number): () => number {
  // mulberry32 — короткий, быстрый, с достаточным для геометрии качеством.
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
